def area(a, h): 
    '''
    Вычисляет площадь треугольника по длине основания и высоте.

    Параметры:
        a: длина основания треугольника
        h: высота, проведённая к основанию

    Возвращаемое значение:
        result: площадь треугольника

    Пример вызова:
        area(6, 4) = 12.0
    '''
    return a * h / 2 

def perimeter(a, b, c): 
    '''
    Вычисляет периметр треугольника по длинам трёх его сторон.

    Параметры:
        a: длина первой стороны треугольника
        b: длина второй стороны треугольника
        c: длина третьей стороны треугольника

    Возвращаемое значение:
        result: периметр треугольника

    Пример вызова:
        perimeter(3, 4, 5) = 12
    '''
    return a + b + c 